//  ===== First part of the code =====

//  1.    Что такое компьютерная сеть и для чего она нужна?

// Компьютерная сеть — это совокупность компьютеров и других устройств, соединённых между собой для обмена данными и совместного использования ресурсов.
// Она позволяет пользователям обмениваться информацией, использовать общие файлы, базы данных и другие ресурсы,
// а также обеспечивает доступ к интернету и другим сетевым сервисам.

//  2.	Чем отличаются LAN и WAN?

// LAN (Local Area Network) — это локальная сеть, которая охватывает малую область, например, офис или дом.
// Она обеспечивает высокую скорость передачи данных и низкую задержку.
// WAN (Wide Area Network) — это глобальная сеть, которая охватывает большие географические области, например, города или страны.

//  3.	Что такое модель OSI? Перечислите её уровни.

// Модель OSI (Open Systems Interconnection) — это концептуальная модель, которая описывает, как данные передаются по сети.
// Уровни модели OSI:

// 1) Физический уровень
// Физический уровень отвечает за передачу битов по физическим средам,
// таким как кабели и радиоволны. Он определяет характеристики оборудования для передачи данных.

// 2) Канальный уровень
// Канальный уровень обеспечивает надежную передачу данных между узлами сети.

// 3) Сетевой уровень
// Сетевой уровень отвечает за маршрутизацию данных между различными сетями и узлами.

// 4) Транспортный уровень
// Транспортный уровень обеспечивает надежную передачу данных между приложениями на разных устройствах.

// 5) Сессионный уровень
// Сессионный уровень управляет установкой, поддержанием и завершением сеансов связи между приложениями.

// 6) Уровень представления
// Уровень представления отвечает за преобразование данных в формат, который может быть понятен приложению.

// 7) Прикладной уровень
// Прикладной уровень обеспечивает интерфейс между приложением и сетью, предоставляя различные сетевые сервисы, такие как электронная почта, веб-серфинг и т.д.

//  4.	Что такое IP-адрес? Чем отличаются IPv4 и IPv6?

// IP-адрес (Internet Protocol address) — это уникальный идентификатор устройства в сети, который используется для его адресации и маршрутизации данных.
// IPv4 — это 32-битовый протокол, который использует адреса в формате XXX.XXX.XXX.XXX.
// IPv6 — это 128-битовый протокол, который использует адреса в формате XXXX:XXXX:XXXX:XXXX:XXXX:XXXX:XXXX:XXXX.

//  5.	Что такое MAC-адрес?

// MAC-адрес (Media Access Control address) — это уникальный идентификатор сетевого интерфейса устройства,
// который используется для его идентификации в локальной сети.

//  6.	Для чего нужны порты? Каков допустимый диапазон номеров портов?

// Порты — это логические точки доступа, которые используются для идентификации конкретных приложений или сервисов на устройстве.
// Допустимый диапазон номеров портов: 0-65535.

//  7.	Что такое сетевой протокол? Приведите три примера.

// Сетевой протокол — это набор правил и стандартов, которые определяют, как данные передаются и обрабатываются в сети.
// Примеры сетевых протоколов: TCP/IP, UDP, ICMP.

// TCP/IP (Transmission Control Protocol/Internet Protocol) — это основной протокол, используемый в интернете для передачи данных.
// UDP (User Datagram Protocol) — это протокол, который обеспечивает передачу данных без установления соединения.
// ICMP (Internet Control Message Protocol) — это протокол, который используется для обмена служебными сообщениями между устройствами в сети.

//  8.	Что такое DNS и какую задачу он решает?

// DNS (Domain Name System) — это система, которая преобразует доменные имена в IP-адреса и обратно.

//  9.	Что такое клиент-серверная архитектура?

// Клиент-серверная архитектура — это модель взаимодействия между клиентами и серверами,
// где клиенты отправляют запросы на сервер, а сервер обрабатывает эти запросы и возвращает ответы.

//  10.	Чем отличаются маршрутизатор и коммутатор?

// Маршрутизатор (Router) — это устройство, которое соединяет различные сети и направляет данные между ними.
// Коммутатор (Switch) — это устройство, которое соединяет устройства внутри одной сети и направляет данные между ними на основе MAC-адресов.

using System.Net;
using System.Net.Sockets;

//  ===== Second parts of the code =====

//  1)

string hostname = Dns.GetHostName();
Console.WriteLine($"Hostname: {hostname}");

//  2)

IPHostEntry hostEntry = Dns.GetHostEntry(hostname);
foreach (IPAddress ip in hostEntry.AddressList)
{
    Console.WriteLine($"IP Address: {ip}");
}

//  3)

foreach (IPAddress ip in hostEntry.AddressList)
{
    if (ip.AddressFamily == System.Net.Sockets.AddressFamily.InterNetwork)
    {
        Console.WriteLine($"IPv4 Address: {ip}");
    }
}

foreach (IPAddress ip in hostEntry.AddressList)
{
    if (ip.AddressFamily == System.Net.Sockets.AddressFamily.InterNetworkV6)
    {
        Console.WriteLine($"IPv6 Address: {ip}");
    }
}

//  4)

foreach (IPAddress ip in hostEntry.AddressList)
{
    Console.WriteLine($"IP Address: {ip}, Address Family: {ip.AddressFamily}");
}

